_CURRENT_LANG = "pt"


def detect_language(default: str = "pt") -> str:
    explicit = None
    for item in sys.argv[1:]:
        if item.startswith("--lang="):
            explicit = item.split("=", 1)[1].strip().lower()
            break
    if explicit in LANGS:
        return explicit

    env = os.getenv("DOCFILL_LANG", "").strip().lower()
    if env in LANGS:
        return env

    locale = os.getenv("LANG", "") or os.getenv("LC_ALL", "") or os.getenv("LC_MESSAGES", "")
    candidate = locale.split(".")[0].split("_")[0].split("-")[0].lower()
    if candidate in LANGS:
        return candidate

    return default


def set_language(code: str) -> None:
    global _CURRENT_LANG
    _CURRENT_LANG = code if code in LANGS else "pt"


def t(key: str) -> str:
    current = LANGS.get(_CURRENT_LANG, LANGS["pt"])
    return current.get(key, LANGS["pt"].get(key, key))


FIELD_LABEL_KEYS = {
    "{{COMPRADOR}}": "field_label_comprador",
    "{{NACIONALIDADE}}": "field_label_nacionalidade",
    "{{PROFISSAO}}": "field_label_profissao",
    "{{ESTADO_CIVIL}}": "field_label_estado_civil",
    "{{CPF_CNPJ}}": "field_label_cpf_cnpj",
    "{{LOTE}}": "field_label_lote",
    "{{QUADRA}}": "field_label_quadra",
    "{{EMPREENDIMENTO}}": "field_label_empreendimento",
    "{{VENDEDOR}}": "field_label_vendedor",
    "{{CIDADE}}": "field_label_cidade",
    "{{DATA}}": "field_label_data",
}


def field_label(marker: str, fallback: str = "") -> str:
    """Translated display label for a DocFill Pro field marker (e.g. '{{COMPRADOR}}')."""
    key = FIELD_LABEL_KEYS.get(marker)
    if key:
        return t(key)
    return fallback or marker
