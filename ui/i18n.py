_CURRENT_LANG = "pt"


def detect_language(default: str = "pt") -> str:
    explicit = None
    for item in sys.argv[1:]:
        if item.startswith("--lang="):
            explicit = item.split("=", 1)[1].strip().lower()
            break
    if explicit in LANGS:
        return explicit

    env = os.getenv("DOCFILL_LANG", "").strip().lower()
    if env in LANGS:
        return env

    locale = os.getenv("LANG", "") or os.getenv("LC_ALL", "") or os.getenv("LC_MESSAGES", "")
    candidate = locale.split(".")[0].split("_")[0].split("-")[0].lower()
    if candidate in LANGS:
        return candidate

    return default


def set_language(code: str) -> None:
    global _CURRENT_LANG
    _CURRENT_LANG = code if code in LANGS else "pt"


def t(key: str) -> str:
    current = LANGS.get(_CURRENT_LANG, LANGS["pt"])
    return current.get(key, LANGS["pt"].get(key, key))
